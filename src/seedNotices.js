async function seedNotices() {
  for (const n of NOTICES) {
    try {
      const done = await get('SELECT value FROM app_settings WHERE key = ?', [n.key]);
      if (done) continue;
      await run('INSERT INTO announcements (kind, title, body) VALUES (?,?,?)', [n.kind, n.title, n.body]);
      await run('INSERT INTO app_settings (key, value) VALUES (?,?)', [n.key, '1']);
      console.log(`[김프리] 공지사항 등록: ${n.title}`);
    } catch (e) {
      console.warn('[김프리] 공지사항 등록 건너뜀:', e.message);
    }
  }
}

